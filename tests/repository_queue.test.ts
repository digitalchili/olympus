import assert from 'node:assert/strict';
import { insertTask, getTask } from '../server/db/queries.js';
import db from '../server/db/index.js';
import { enqueueRepositoryTask, claimRepositoryTask, finishRepositoryTask, repositoryOwner, setRepositoryBlocker, recordRepositoryRun } from '../server/db/repository-queue.js';

const a = insertTask({ title: 'Implement login', status: 'in_progress' });
const b = insertTask({ title: 'Add settings', status: 'in_progress' });
const c = insertTask({ title: 'Another repository', status: 'in_progress' });
enqueueRepositoryTask('github:42', a.id);
enqueueRepositoryTask('github:42', b.id);
enqueueRepositoryTask('github:43', c.id);
assert.equal(claimRepositoryTask('github:42', b.id), null, 'later tasks cannot overtake the first');
const first = claimRepositoryTask('github:42', a.id)!;
assert.ok(first.token);
assert.equal(claimRepositoryTask('github:42', b.id), null);
assert.ok(claimRepositoryTask('github:43', c.id), 'different repositories remain concurrent');
recordRepositoryRun(a.id, 'run-a');
assert.equal(repositoryOwner('github:42')?.runId, 'run-a');
assert.equal(getTask(b.id)?.repositoryQueue?.message, 'Waiting for “Implement login” to finish. Your request is saved and will start automatically.');
setRepositoryBlocker('github:42', first.token, 'The previous task needs attention. Its saved work is safe.');
assert.equal(getTask(b.id)?.repositoryQueue?.state, 'blocked');
assert.equal(claimRepositoryTask('github:42', a.id)?.token, first.token, 'recovery keeps the same durable owner');
assert.equal(finishRepositoryTask('github:42', 'stale-token'), false);
assert.equal(repositoryOwner('github:42')?.taskId, a.id);
assert.equal(finishRepositoryTask('github:42', first.token), true);
const second = claimRepositoryTask('github:42', b.id)!;
assert.notEqual(second.token, first.token);
assert.equal(finishRepositoryTask('github:42', first.token), false, 'old worker cannot release its replacement');
assert.equal(repositoryOwner('github:42')?.taskId, b.id);
assert.equal(db.prepare('SELECT owner_task_id FROM repository_workflows WHERE repository_key=?').get('github:42')?.owner_task_id, b.id, 'ownership is durable, not a timer or process-local map');
console.log('Repository queue ownership tests passed');

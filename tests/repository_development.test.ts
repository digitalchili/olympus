import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createProjectCpService } from '../server/project-cp.js';
import { createProject, upsertProjectRepositoryLink } from '../server/db/projects.js';
import { upsertGitHubInstallation } from '../server/db/studio-projects.js';
import { insertTask, getTask } from '../server/db/queries.js';
import { captureCodingBaseline, verifyCodingRun } from '../server/coding-verification.js';
import { createRepositoryDevelopment } from '../server/repository-development.js';
import { createRepositoryQueue } from '../server/repository-queue.js';
import { createTaskAgentRun, finishTaskAgentRun } from '../server/db/task-agent-runs.js';
import { repositoryOwner } from '../server/db/repository-queue.js';
import { configureQueuedMessageDispatcher } from '../server/queued-message-dispatcher.js';
import { putQueuedTaskMessage } from '../server/db/task-message-queue.js';

const root = process.env.OLYMPUS_DISPATCH_HOME!;
const git = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const seed = join(root, 'seed'); const remote = join(root, 'remote.git'); const checkouts = join(root, 'checkouts');
await mkdir(seed); await mkdir(checkouts);
git(seed, 'init', '-b', 'main'); git(seed, 'config', 'user.name', 'Fixture'); git(seed, 'config', 'user.email', 'fixture@example.invalid');
await mkdir(join(seed, '.olympus'));
await writeFile(join(seed, '.olympus/verification.json'), JSON.stringify({ commands: [[process.execPath, '-e', 'process.exit(0)']] }));
await writeFile(join(seed, 'base.txt'), 'baseline');
git(seed, 'add', '.'); git(seed, 'commit', '-m', 'Initial'); git(root, 'clone', '--bare', seed, remote);
const original = git(seed, 'rev-parse', 'HEAD');
upsertGitHubInstallation({ id: 77, accountLogin: 'fixture', accountType: 'Organization', permissionMode: 'read_write' });
const project = createProject({ name: 'Automatic tasks', purpose: 'Check automatic handoffs', managerProfileId: 'default', changedBy: 'test' });
const link = upsertProjectRepositoryLink(project.id, 77, { id: 9001, name: 'fixture', fullName: 'fixture/repo', owner: 'fixture', private: false, defaultBranch: 'main', htmlUrl: 'https://example.invalid/repo', cloneUrl: remote });
const cp = createProjectCpService({ rootDir: checkouts });
const development = createRepositoryDevelopment(checkouts);
let backgroundAvailable = true; let backgroundActive = false;
const scheduled: string[] = [];
configureQueuedMessageDispatcher({ schedule: id => { scheduled.push(id); } });
const queue = createRepositoryQueue({ rootDir: checkouts, adapter: { async getBackgroundWork() {
  return { available: backgroundAvailable, work: backgroundActive ? [{ id: 'child', kind: 'delegation' as const, status: 'running' }] : [], continuation: { status: 'none' as const } };
} } });
const prepare = (taskId: string) => cp.prepareTask({ projectId: project.id, taskId, profileId: 'default', repositoryLink: link, automaticHandoff: true });
const a = insertTask({ title: 'Task A', status: 'in_progress', project_id: project.id });
assert.equal(await queue.admit(a), true);
createTaskAgentRun({ taskId: a.id, runId: 'run-a', status: 'streaming', kind: 'chat', startedAt: Date.now() });
const leaseA = await prepare(a.id);
await captureCodingBaseline(getTask(a.id)!, 'run-a');
await writeFile(join(leaseA.workdir, 'a.txt'), 'checked work from A');
await development.checkpoint(leaseA);
await assert.rejects(development.accept(getTask(a.id)!, 'run-a', leaseA, link), /checks/i);
assert.equal(await verifyCodingRun(getTask(a.id)!, 'run-a'), true);
const accepted = await development.accept(getTask(a.id)!, 'run-a', leaseA, link);
assert.equal(accepted, git(leaseA.workdir, 'rev-parse', 'HEAD'));
assert.equal(await development.accept(getTask(a.id)!, 'run-a', leaseA, link), accepted, 'retry after an interrupted receipt is idempotent');
const b = insertTask({ title: 'Task B', status: 'in_progress', project_id: project.id });
putQueuedTaskMessage({ taskId: b.id, id: 'request-b', content: 'Build B', settings: {}, invitedProfileIds: [], collaborationScope: 'discussion', confirmPersistentCollaboration: false, createdAt: Date.now(), updatedAt: Date.now() });
assert.equal(await queue.admit(b), false);
finishTaskAgentRun('run-a', 'done');
backgroundActive = true;
await queue.tick();
assert.equal(repositoryOwner('github:9001')?.taskId, a.id, 'native children retain repository ownership');
backgroundActive = false; backgroundAvailable = false;
await queue.tick();
assert.equal(repositoryOwner('github:9001')?.taskId, a.id, 'unknown native state fails closed');
backgroundAvailable = true;
await queue.tick();
assert.equal(repositoryOwner('github:9001'), undefined, 'successful checked work hands off automatically');
assert.ok(scheduled.includes(b.id), 'the next saved request is dispatched without user input');
assert.equal(await queue.admit(b), true);
const leaseB = await prepare(b.id);
assert.equal(leaseB.baseSha, accepted, 'B starts at the exact accepted commit');
assert.equal(await readFile(join(leaseB.workdir, 'a.txt'), 'utf8'), 'checked work from A');
await captureCodingBaseline(getTask(b.id)!, 'run-b');
await writeFile(join(leaseB.workdir, 'unfinished.txt'), 'not accepted');
await development.checkpoint(leaseB);
await assert.rejects(development.accept(getTask(b.id)!, 'run-b', leaseB, link), /checks/i);
const c = insertTask({ title: 'Source probe only', status: 'in_progress', project_id: project.id });
const leaseC = await prepare(c.id);
assert.equal(leaseC.baseSha, accepted, 'unverified B cannot become another task’s source');
await assert.rejects(readFile(join(leaseC.workdir, 'unfinished.txt')));
assert.equal(git(remote, 'rev-parse', 'main'), original, 'automatic handoff never publishes to GitHub');
assert.equal(git(leaseA.workdir, 'status', '--porcelain'), '');
console.log('Checked development handoff tests passed');
// A new upstream commit must be included in the recorded starting version.
await writeFile(join(seed, 'upstream.txt'), 'latest remote work');
git(seed, 'add', '.'); git(seed, 'commit', '-m', 'Upstream update'); git(seed, 'push', remote, 'main');
const d = insertTask({ title: 'New upstream source', status: 'in_progress', project_id: project.id });
const leaseD = await prepare(d.id);
assert.equal(leaseD.baseSha, git(leaseD.workdir, 'rev-parse', 'HEAD'));
// A previously released task must also receive the accepted source when reopened.
const { releaseProjectEditor } = await import('../server/db/project-cp.js');
releaseProjectEditor({ leaseId: leaseC.id, taskId: c.id });
await prepare(c.id);
assert.equal(await readFile(join(leaseC.workdir, 'upstream.txt'), 'utf8'), 'latest remote work');
// Do not finish or abort a Git operation that belongs to the task.
const mergeHead = join(leaseD.workdir, '.git', 'MERGE_HEAD');
await writeFile(mergeHead, original + '\n');
await assert.rejects(development.checkpoint(leaseD), /unfinished Git operation/);
assert.equal(await readFile(mergeHead, 'utf8'), original + '\n');
await assert.rejects(prepare(d.id), /unfinished Git operation/);
assert.equal(await readFile(mergeHead, 'utf8'), original + '\n');
